"""Service to generate unique names for papers based on their metadata."""
import logging
import re
import xml.etree.ElementTree as ET
from typing import Dict

from app.utils.sanitizer import sanitize_filename
from app.repositories.registry_repository import RegistryRepository

logger = logging.getLogger(__name__)

class PaperNamer:
    """Generates unique names for papers based on their metadata."""

    #GROBID utilizza il namespace TEI
    NS = {"tei": "http://www.tei-c.org/ns/1.0"}

    # List of common stop words to exclude from keywords
    STOP_WORDS = {
        "a",
        "an",
        "the",
        "on",
        "of",
        "for",
        "in",
        "with",
        "by",
        "at",
        "to",
        "and",
        "or",
        "using",
        "based",
        "study",
        "analysis",
        "approach",
        "effect",
        "impact",
        "via",
        "through",
        "during",
    }

    def __init__(self, registry_repo: RegistryRepository):
        self._registry_repo = registry_repo

    def resolve_standard_paper_name(self, tei_element: ET.Element, document_hash: str) -> str:
        """Generates a standard paper name based on the metadata extracted from the TEI XML file.
        
        Args:
            tei_element (ET.Element): Parsed TEI XML element.
            
        Returns:
            str: A standardized paper name in the format "{first_author}{YYYY}{keyword}".
        """
        document_record = self._registry_repo.is_document_registered(document_hash=document_hash)

        if document_record is not None:
            logger.info(f"Document {document_hash} is already registered with title '{document_record.title}'.")
            return document_record.title

        return self._generate_unique_paper_name(tei_element)

    def _generate_unique_paper_name(self, tei_element: ET.Element) -> str:
            metadata = self._get_metadata_from_tei(tei_element)
            keyword = self._extract_keyword_from_title(metadata["title"])
            
            candidate = f"{metadata['first_author']}{metadata['year']}{keyword}"
            i = 0
            while self._registry_repo.is_title_registered(candidate):
                i += 1
                candidate = f"{candidate}_{i}"
            
            self._registry_repo.reserve_title(candidate)
            return candidate

    def _get_metadata_from_tei(self, tei_element: ET.Element) -> Dict[str, str]:
        """Extracts metadata from a TEI XML file generated by GROBID.
        
        Args:
            tei_element (ET.Element): Parsed TEI XML element.
            
        Returns:
            dict: A dictionary containing the title, first author, and year of publication.
        """
        root = tei_element

        title_elem = root.find(".//tei:titleStmt/tei:title", self.NS)
        title = (
            title_elem.text.strip()
            if title_elem is not None and title_elem.text
            else ""
        )

        author_elem = root.find(".//tei:analytic/tei:author[1]//tei:surname", self.NS)
        if author_elem is None:
            author_elem = root.find(".//tei:author[1]//tei:surname", self.NS)
        if author_elem is None:
            author_elem = root.find(".//tei:author[1]", self.NS)

        first_author = (
            author_elem.text.strip().split()[-1]
            if author_elem is not None and author_elem.text
            else "Unknown"
        )

        date_elem = root.find(".//tei:publicationStmt//tei:date[@when]", self.NS)
        year = "ND"

        if date_elem is not None:
            when_val = date_elem.get("when", "")

            match = re.match(r"^(\d{4})", when_val)
            if match:
                year = match.group(1)

        return {
            "title": sanitize_filename(title.lower()),
            "first_author": sanitize_filename(first_author.lower()),
            "year": sanitize_filename(year),
        }

    def _extract_keyword_from_title(self, title):
        """Extracts a keyword from the title, filtering out stop words.
        
        Args:
            title (str): The title of the paper.
            
        Returns:
            str: A keyword extracted from the title, or an empty string if none found."""
        words = re.sub(r"[^\w\s]", "", title).split()

        keywords = [
            w
            for w in words
            if w.lower() not in self.STOP_WORDS and len(w) > 2 and not w.isdigit()
        ]

        selected = keywords[:1]
        return selected[0] if selected else "paper"
