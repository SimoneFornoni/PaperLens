"""Service to generate unique names for papers based on their metadata."""
import logging
import re
import xml.etree.ElementTree as ET
from typing import Dict

from backend.app.utils.sanitizer import sanitize_filename

logger = logging.getLogger(__name__)

class PaperNamer:
    """Generates unique names for papers based on their metadata."""

    #GROBID utilizza il namespace TEI
    NS = {"tei": "http://www.tei-c.org/ns/1.0"}

    # List of common stop words to exclude from keywords
    STOP_WORDS = {
        "a",
        "an",
        "the",
        "on",
        "of",
        "for",
        "in",
        "with",
        "by",
        "at",
        "to",
        "and",
        "or",
        "using",
        "based",
        "study",
        "analysis",
        "approach",
        "effect",
        "impact",
        "via",
        "through",
        "during",
    }

    def _get_metadata_from_tei(self, tei_path: str) -> Dict[str, str]:
        """Extracts metadata from a TEI XML file generated by GROBID.
        
        Args:
            tei_path (str): Path to the TEI XML file.
            
        Returns:
            dict: A dictionary containing the title, first author, and year of publication.
        """
        content = tei_path.read_bytes()
        root = ET.fromstring(content)

        title_elem = root.find(".//tei:titleStmt/tei:title", self.NS)
        title = (
            title_elem.text.strip()
            if title_elem is not None and title_elem.text
            else ""
        )

        author_elem = root.find(".//tei:analytic/tei:author[1]//tei:surname", self.NS)
        if author_elem is None:
            author_elem = root.find(".//tei:author[1]//tei:surname", self.NS)
        if author_elem is None:
            author_elem = root.find(".//tei:author[1]", self.NS)

        first_author = (
            author_elem.text.strip().split()[-1]
            if author_elem is not None and author_elem.text
            else "Unknown"
        )

        date_elem = root.find(".//tei:publicationStmt//tei:date[@when]", self.NS)
        year = "ND"

        if date_elem is not None:
            when_val = date_elem.get("when", "")

            match = re.match(r"^(\d{4})", when_val)
            if match:
                year = match.group(1)

        return {
            "title": title.lower(),
            "first_author": first_author.lower(),
            "year": year,
        }

    def _extract_keyword_from_title(self, title):
        """Extracts a keyword from the title, filtering out stop words.
        
        Args:
            title (str): The title of the paper.
            
        Returns:
            str: A keyword extracted from the title, or an empty string if none found."""
        words = re.sub(r"[^\w\s]", "", title).split()

        keywords = [
            w
            for w in words
            if w.lower() not in self.STOP_WORDS and len(w) > 2 and not w.isdigit()
        ]

        selected = keywords[:1]
        return selected[0] if selected else "paper"


    def generate_standard_paper_name(self, xml_path):
        """Generates a standard paper name based on the metadata extracted from the TEI XML file.
        
        Args:
            xml_path (str): Path to the TEI XML file.
            
        Returns:
            str: A standardized paper name in the format "first_author_YYYY_keyword.pdf".
        """
        metadata = self._get_metadata_from_tei(xml_path)
        keyword = self._extract_keyword_from_title(metadata["title"])
        return f"{metadata['first_author']}_{metadata['year']}_{keyword}.pdf"
